#!/usr/bin/env python3
"""
Kopi 10-cent margin model  (Team 1 / Kaya Kopi, 24 Nov 2026)

Built to the client's 24 Nov instruction (Serene Lim):
  "No recipe cards, no target margin, no price-change history.
   State your assumptions and show me how the answer changes."

Design
------
* Every INGREDIENT PRICE is EVIDENCE from the 69 scanned supplier invoices
  (build/out/invoices.json): kopi, sugar, and the milk cartons.
* Every RECIPE QUANTITY is an ASSUMPTION (the client gave none) and is flagged.
* The headline verdict is the part that does NOT depend on the unknowns:
  a +S$0.10 price adds S$0.10 to every cup, and it is profitable unless
  demand falls by more than step/new-price  (0.10/1.70 = 5.9%)  -- independent
  of ingredient cost.  The cost build-up is shown to bound the range.

Run:  .venv/bin/python build/margin_model.py   ->  build/out/kopi_margin_model.md
"""
from __future__ import annotations
import json, os, statistics as st

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))      # repo root (build/.. = repo)
INV  = os.path.join(ROOT, "build", "out", "invoices.json")

# --------------------------------------------------------------------------- #
# A) EVIDENCE - ingredient prices (S$) from the 69 scans, Aug 2025 - Jun 2026
# --------------------------------------------------------------------------- #
def med(sup, kw):
    inv = json.load(open(INV)); ups = []
    for v in inv:
        if (v.get("supplier_name") or "") != sup:  continue
        for ln in v.get("lines") or []:
            if kw in (ln.get("name") or "").lower():
                up = ln.get("unit_price")
                if isinstance(up, (int, float)):  ups.append(up)
    return st.median(ups) if ups else None

KOPISG_KG   = 13.54    # Heng Huat "Kopi powder 5kg" 67.70/5   (range 13.18-13.99)
COND_CARTON = 48.13    # Mewah "Condensed milk ctn" median      (range 44.99-50.71)
EVA_CARTON  = 44.92    # Mewah "Evaporated milk ctn" median     (range 41.78-46.05)
SUGAR_KG    = 1.70     # Mewah "Sugar 25kg" 42.59/25           (range 1.66-1.75)

# Milk: carton net mass is NOT legible on the scans.  A ~S$44-48 carton is
# realistically a case of 24 x 400 ml tins (~9.6 L) -> ~S$5/L, which matches
# Singapore evaporated/condensed pricing.  Base = 24 tins; sensitivity 12-48.
TINS_BASE   = 24
TIN_L       = 0.40
def milk_per_L(carton_s, tins=TINS_BASE):
    litres = tins * TIN_L
    return carton_s / litres
COND_L = milk_per_L(COND_CARTON)      # ~5.01 S$/L
EVA_L  = milk_per_L(EVA_CARTON)       # ~4.68 S$/L

# --------------------------------------------------------------------------- #
# B) ASSUMPTIONS - recipe per cup (client supplied NONE) - take-away kopi-C
# --------------------------------------------------------------------------- #
REC = {"coffee_g": 5.0, "condensed_ml": 25, "evap_ml": 15, "sugar_g": 0}
PACK_COST = 0.05                 # S$ paper cup + lid            (ASSUMPTION)
PRICE_BASE = 1.60                # menu base price (menu_items.base_price, item 1)
PRICE_STEP = 0.10                # the client's question: +10 cents

# Sales base (EVIDENCE: POS item_id=1 'Kopi', 01 Jul 2025 - 30 Jun 2026)
CUPS_TOTAL, ACTIVE_DAYS = 2252, 363
DAILY = CUPS_TOTAL / ACTIVE_DAYS       # ~6.2 cups/day

def cost_per_cup(rec=REC, cond_l=COND_L, eva_l=EVA_L, pack=PACK_COST):
    return (rec["coffee_g"]/1000*KOPISG_KG
            + rec["condensed_ml"]/1000*cond_l
            + rec["evap_ml"]/1000*eva_l
            + rec["sugar_g"]/1000*SUGAR_KG
            + pack)

def main():
    c0 = cost_per_cup()
    gp0 = PRICE_BASE - c0
    gp1 = PRICE_BASE + PRICE_STEP - c0
    # Break-even demand loss for +10c (revenue-neutral):  (P0+step)*(1-x) = P0
    #   ->  x = 1 - P0/(P0+step)  =  step/(P0+step).  INDEPENDENT of cost.
    x_be = PRICE_STEP / (PRICE_BASE + PRICE_STEP)        # 0.10/1.70 = 5.88%

    A = []
    ap = A.append
    ap("# Kopi 10-cent margin model (assumption-based, per client instruction)")
    ap("")
    ap(f"_Generated by `build/margin_model.py` (reproducible). Base = {DAILY:.1f} Kopi cups/day "
       f"(POS item 1, Jul 2025 - Jun 2026); price base = S${PRICE_BASE:.2f}._")
    ap("")
    ap("## 1. What we can evidence (69 scanned invoices, Aug 2025 - Jun 2026)")
    ap("")
    ap("| input | supplier | price (S$) | note |")
    ap("|---|---|---|---|")
    ap(f"| roasted kopi | Heng Huat | **{KOPISG_KG:.2f}/kg** (13.18-13.99) | rising +6.1% over window |")
    ap(f"| condensed milk | Mewah | {COND_CARTON:.2f}/carton (44.99-50.71) | carton net mass not legible |")
    ap(f"| evaporated milk | Mewah | {EVA_CARTON:.2f}/carton (41.78-46.05) | carton net mass not legible |")
    ap(f"| sugar | Mewah | **{SUGAR_KG:.2f}/kg** (1.66-1.75) | flat |")
    ap(f"| Kopi sales | POS item 1 | {CUPS_TOTAL} cups / {ACTIVE_DAYS} days = **{DAILY:.1f}/day** | realized S$1.84/cup (57% @1.60, 43% @2.16) |")
    ap("")
    ap("The **roasted-kopi input is rising** (S$13.18 -> 13.99/kg) - that part is solid evidence.")
    ap("What is NOT in the data: the recipe, the milk-carton net mass, packaging, labour, rent, "
       "and any target margin. So the cost-per-cup below is a **model on stated assumptions** - "
       "which is exactly what you asked us to show.")
    ap("")
    ap("## 2. Per-cup cost build-up (each quantity is an assumption)")
    ap("")
    ap("| component | assumption | unit price (S$) | cost/cup (S$) |")
    ap("|---|---|---|---|")
    ap(f"| roasted kopi | {REC['coffee_g']:.0f} g | {KOPISG_KG:.2f}/kg | {REC['coffee_g']/1000*KOPISG_KG:.3f} |")
    ap(f"| condensed milk | {REC['condensed_ml']:.0f} ml | {COND_L:.2f}/L | {REC['condensed_ml']/1000*COND_L:.3f} |")
    ap(f"| evaporated milk | {REC['evap_ml']:.0f} ml | {EVA_L:.2f}/L | {REC['evap_ml']/1000*EVA_L:.3f} |")
    ap(f"| sugar | {REC['sugar_g']:.0f} g | {SUGAR_KG:.2f}/kg | {REC['sugar_g']/1000*SUGAR_KG:.3f} |")
    ap(f"| cup + lid | - | {PACK_COST:.2f} | {PACK_COST:.3f} |")
    ap(f"| **ingredient cost/cup (base)** |  |  | **{c0:.3f}** |")
    ap("")
    ap(f"*Milk per-litre assumes a {TINS_BASE} x 400 ml carton (net mass not legible on the scans); "
       "this is the single biggest assumption and is bounded in section 4.*")
    ap("")
    ap("## 3. The 10-cent answer  (headline - this part does not depend on the recipe)")
    ap("")
    ap(f"* **+S${PRICE_STEP:.2f} to every cup sold.** At S${PRICE_BASE:.2f} the ingredient margin is "
       f"S${gp0:.3f}/cup ({gp0/PRICE_BASE*100:.0f}%); at S${PRICE_BASE+PRICE_STEP:.2f} it is "
       f"S${gp1:.3f}/cup ({gp1/(PRICE_BASE+PRICE_STEP)*100:.0f}%). Either way +10c is a net gain per cup.")
    ap(f"* **On {DAILY:.1f} cups/day: +10c = +S${PRICE_STEP*DAILY:.2f}/day** (zero demand loss).")
    ap(f"* **Break-even:** +10c is profitable unless demand falls by more than **{x_be*100:.1f}%** "
       f"(= S$0.10 / S$1.70). That is losing ~{x_be*DAILY:.1f} of the {DAILY:.1f} cups/day. "
       "**This threshold does not change with ingredient cost** - so the missing recipe does not "
       "block the decision; the only unknown is the demand response, which your data cannot answer.")
    ap("")
    ap("## 4. How the answer changes (as requested)")
    ap("")
    ap("### 4a. Milk-carton size  ->  cost/cup (the biggest assumption)")
    ap("")
    ap("| carton tins | milk S$/L | cost/cup (S$) | ingredient margin @1.60 |")
    ap("|---|---|---|---|")
    for tins in (12, 24, 48):
        cl, el = milk_per_L(COND_CARTON, tins), milk_per_L(EVA_CARTON, tins)
        cc = cost_per_cup(cond_l=cl, eva_l=el)
        ap(f"| {tins} | {cl:.2f}/{el:.2f} | {cc:.3f} | {(1.60-cc)/1.60*100:.0f}% |")
    ap("")
    ap("> Even at a 12-tin carton (worst case, ~S$10/L milk) the ingredient cost is ~S$0.45/cup and "
       "the +10c gain per cup is unchanged. The verdict is robust to this assumption.")
    ap("")
    ap("### 4b. Demand response to +10c  (revenue/day, correct formula)")
    ap("")
    ap("Revenue = price x cups. Old = S$1.60 x cups; New = S$1.70 x (cups after loss). "
       "Delta/day = (1.70 x D x (1 - lost%)) - (1.60 x D). The +10c is earned on the cups kept, "
       "but the full S$1.60 is lost on the cups that walk.")
    ap("")
    ap("| cups lost | old revenue/day | new revenue/day | delta/day (S$) |")
    ap("|---|---|---|---|")
    for e in (0.0, 0.05, x_be, 0.10, 0.20):
        old_r = PRICE_BASE*DAILY
        new_r = (PRICE_BASE+PRICE_STEP)*DAILY*(1-e)
        delta = new_r - old_r
        flag = "  <- break-even" if abs(e-x_be) < 1e-9 else ""
        ap(f"| {e*100:.1f}%{flag} | {old_r:.2f} | {new_r:.2f} | {delta:+.2f} |")
    ap("")
    ap(f"> **Break-even = {x_be*100:.1f}% demand loss** (S$0.10/S$1.70), independent of ingredient cost. "
       "Above that, the raise loses money. A 10% demand drop (a very plausible reaction to a 6% price rise) "
       "would cost about S$0.43/day - i.e. the raise would **not** pay off. This is why the demand "
       "response is the decision-critical unknown, and why a monitored price test is the safe path.")
    ap("")
    ap("### 4c. If the realized price already includes the raise (S$1.84 realized)")
    ap("")
    ap(f"* 43% of Kopi transactions already bill at S$2.16 (the other 57% at S$1.60) - i.e. a two-price "
       f"mix, not a single price. If S$1.70 were a chain-wide floor, the same +10c logic applies per cup.")
    ap("")
    ap("## 5. Assumptions to confirm (none were supplied by Finance)")
    ap("")
    ap(f"1. Recipe per cup: coffee g, condensed ml, evaporated ml, sugar g (model: 5g / 25ml / 15ml / 0).")
    ap(f"2. Milk carton net mass (model used {TINS_BASE} x 400 ml).")
    ap(f"3. Packaging cost per cup (model used S${PACK_COST:.2f}).")
    ap("4. Whether the realized S$1.84/cup is GST-inclusive (menu base S$1.60; 43% of tx @ S$2.16).")
    ap("5. Any target margin / cost-to-serve benchmark (not provided).")
    ap("")
    ap("## 6. Plain-English conclusion")
    ap("")
    ap(f"Raising Kopi by S$0.10 (S${PRICE_BASE:.2f} -> S${PRICE_BASE+PRICE_STEP:.2f}) **adds S$0.10 to every "
       f"cup sold** - about **S${PRICE_STEP*DAILY:.2f}/day** at current volume - and it only loses money if "
       f"you lose more than **{x_be*100:.1f}%** of kopi cups. Because the +10c is pure margin on each cup, "
       f"the ingredient cost (which we could not confirm) does not change this: even at a pessimistic "
       f"S$0.45/cup cost the raise is a net gain per cup. The real risk is **demand**, which the data "
       "cannot measure. **Recommendation: a monitored, reversible price test** (one outlet, 4-6 weeks, "
       "track cups/day and revenue/day) rather than a blind chain-wide jump.")
    ap("")

    path = os.path.join(ROOT, "build", "out", "kopi_margin_model.md")
    open(path, "w").write("\n".join(A) + "\n")

    print("="*66)
    print("Kopi 10-cent margin model - SUMMARY")
    print("="*66)
    print(f"  cost/cup (base, 24-tin milk) : S${c0:.3f}")
    print(f"  ingredient margin @1.60      : S${gp0:.3f}  ({gp0/PRICE_BASE*100:.0f}%)")
    print(f"  +10c / cup                   : S${PRICE_STEP:.2f}   ->  +S${PRICE_STEP*DAILY:.2f}/day")
    print(f"  breakeven demand loss        : {x_be*100:.1f}%  (cost-independent)")
    print(f"  wrote                        : {path}")

if __name__ == "__main__":
    main()
