CREATE TABLE public.openai_usage_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id uuid NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now(),
    user_id uuid REFERENCES auth.users (id) ON DELETE SET NULL,
    purpose text NOT NULL CHECK (purpose IN ('chat', 'ocr', 'embedding', 'other')),
    endpoint text NOT NULL CHECK (endpoint IN ('chat/completions', 'embeddings')),
    requested_model text NOT NULL,
    returned_model text,
    input_tokens bigint CHECK (input_tokens IS NULL OR input_tokens >= 0),
    output_tokens bigint CHECK (output_tokens IS NULL OR output_tokens >= 0),
    cached_input_tokens bigint CHECK (
        cached_input_tokens IS NULL OR cached_input_tokens >= 0
    ),
    reasoning_tokens bigint CHECK (reasoning_tokens IS NULL OR reasoning_tokens >= 0),
    estimated_cost_usd numeric(18, 10),
    pricing_version text,
    provider_response_id text,
    provider_request_id text,
    http_status integer NOT NULL CHECK (http_status BETWEEN 100 AND 599),
    error_code text
);

CREATE INDEX openai_usage_events_created_at_idx
    ON public.openai_usage_events (created_at DESC);
CREATE INDEX openai_usage_events_user_created_at_idx
    ON public.openai_usage_events (user_id, created_at DESC);

ALTER TABLE public.openai_usage_events ENABLE ROW LEVEL SECURITY;

